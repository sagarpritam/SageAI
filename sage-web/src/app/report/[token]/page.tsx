import { Shield, Sparkles, AlertTriangle } from "lucide-react";
import Link from "next/link";
import { RiskGauge } from "@/components/RiskGauge";
import { VulnerabilityList } from "@/components/VulnerabilityList";

// Server Component
export default async function PublicReportPage({
  params,
}: {
  params: Promise<{ token: string }>;
}) {
  const { token } = await params;
  const backendUrl = process.env.API_URL || "http://localhost:8000";

  let scanData = null;
  let error = null;

  try {
    const res = await fetch(`${backendUrl}/scan/public/${token}`, {
      cache: "no-store", // Or revalidate if we want edge caching
    });

    if (!res.ok) {
      error = "Report not found or link has expired.";
    } else {
      scanData = await res.json();
    }
  } catch (e) {
    console.error("Failed to fetch public report", e);
    error = "Could not load report data.";
  }

  if (error || !scanData) {
    return (
      <div className="min-h-screen bg-black text-emerald-50 flex flex-col items-center justify-center p-4">
        <Shield className="w-16 h-16 text-zinc-700 mb-6" />
        <h1 className="text-2xl font-mono text-zinc-400 mb-4">{error || "Loading..."}</h1>
        <Link href="/" className="text-emerald-500 hover:text-emerald-400 font-mono underline">
          Run your own scan with SageAI
        </Link>
      </div>
    );
  }

  return (
    <main className="min-h-screen bg-black text-emerald-50 font-sans selection:bg-emerald-500/30">
      <div className="absolute inset-0 bg-[radial-gradient(ellipse_at_top,_var(--tw-gradient-stops))] from-emerald-900/20 via-black to-black z-0 pointer-events-none" />

      {/* Viral CTA Banner */}
      <div className="relative z-20 w-full bg-emerald-500 text-black py-3 px-4 flex flex-col sm:flex-row items-center justify-center gap-4 shadow-[0_0_20px_rgba(16,185,129,0.4)]">
        <div className="flex items-center gap-2 font-bold flex-wrap justify-center text-sm sm:text-base">
          <Sparkles className="w-5 h-5" />
          <span>This is a read-only security report generated by SageAI.</span>
        </div>
        <Link 
          href="/" 
          className="bg-black text-emerald-400 px-5 py-1.5 rounded-full font-bold text-sm hover:bg-zinc-900 transition-colors whitespace-nowrap"
        >
          Run a Free Scan
        </Link>
      </div>

      <div className="relative z-10 max-w-5xl mx-auto px-4 py-12 space-y-16">
        
        {/* Header */}
        <div className="text-center space-y-4">
          <div className="inline-flex p-4 bg-emerald-900/30 rounded-full mb-2">
            <Shield className="w-10 h-10 text-emerald-500" />
          </div>
          <h1 className="text-4xl md:text-5xl font-black mb-2">Security Assessment Report</h1>
          <p className="text-xl text-zinc-400 font-mono">Target: <span className="text-emerald-400">{scanData.target}</span></p>
          <p className="text-sm text-zinc-500 font-mono">Scanned on: {new Date(scanData.timestamp).toLocaleString()}</p>
        </div>

        {/* Risk Overview */}
        <section className="flex flex-col items-center bg-zinc-950/50 border border-emerald-900/30 rounded-2xl p-8">
          <h2 className="text-2xl font-bold mb-8 text-emerald-400">Risk Assessment</h2>
          <RiskGauge 
            score={scanData.risk_summary.risk_score} 
            level={scanData.risk_summary.risk_level} 
            totalFindings={scanData.findings.length} 
          />
        </section>

        {/* Findings List */}
        <section>
          <div className="flex items-center justify-between border-b border-white/10 pb-4 mb-6">
            <h2 className="text-2xl font-black text-emerald-400 flex items-center gap-2">
              <AlertTriangle className="w-6 h-6" /> Identified Vulnerabilities
            </h2>
            <span className="font-mono text-zinc-500 text-sm">{scanData.findings.length} findings</span>
          </div>
          
          <VulnerabilityList vulnerabilities={scanData.findings} />
        </section>

        {/* Footer CTA */}
        <div className="mt-20 py-12 border-t border-emerald-900/30 text-center space-y-6">
          <h3 className="text-3xl font-black tracking-tight text-white">Protect your own attack surface</h3>
          <p className="text-zinc-400 max-w-lg mx-auto">
            SageAI autonomous agents find critical vulnerabilities in 60 seconds.
          </p>
          <Link 
            href="/"
            className="inline-block px-8 py-4 bg-emerald-500 hover:bg-emerald-400 text-black font-bold rounded-lg shadow-[0_0_30px_rgba(16,185,129,0.3)] transition-all hover:scale-105"
          >
            Start your free scan today →
          </Link>
        </div>

      </div>
    </main>
  );
}
