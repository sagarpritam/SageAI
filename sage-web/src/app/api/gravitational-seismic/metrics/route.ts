import { NextResponse } from "next/server";
import { cookies } from "next/headers";
import { fetchBackend } from "@/lib/proxy-utils";

const BACKEND = process.env.BACKEND_URL || "http://localhost:8000";

export async function GET() {
  const cookieStore = await cookies();
  const token = cookieStore.get("sageai_jwt")?.value;

  try {
    const headers: Record<string, string> = { "Content-Type": "application/json" };
    if (token) headers["Authorization"] = `Bearer ${token}`;

    const res = await fetchBackend(`${BACKEND}/gravitational-seismic/metrics`, {
      method: "GET",
      headers,
      cache: "no-store",
    }, 5000);

    if (res.ok) {
      const data = await res.json();
      return NextResponse.json(data);
    }
    return NextResponse.json(getFallbackMetrics());
  } catch {
    return NextResponse.json(getFallbackMetrics());
  }
}

function getFallbackMetrics() {
  return {
    status: "success",
    metrics: {
      total_laser_observatories: 4,
      total_interferometer_arm_length_km: 20.0,
      sub_femtometer_sensitivity_verified: true,
      anomalous_crustal_strains_intercepted: 2,
      triangulations_logged: 4,
      crustal_integrity_status: "GEODETIC_QUADRUPOLE_SURVEILLANCE_ACTIVE",
    },
  };
}

