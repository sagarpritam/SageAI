"""DevSecOps CI/CD Router.

Provides automated pipeline integration for GitHub Actions, GitLab CI,
and Jenkins:
- Parallel security quality gates
- Policy threshold checks (fail on critical/high)
- SagePatch closed-loop auto-remediation PRs
"""

from typing import Any, Dict, List, Optional

from fastapi import APIRouter, Depends, HTTPException, Request, status
from pydantic import BaseModel, Field
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.database import get_db
from app.core.rate_limit import limiter
from app.core.security import get_current_user, require_role
from app.models.organization import Organization
from app.services.audit_service import log_audit_event
from app.services.ci_gate_service import execute_ci_gate_loop

router = APIRouter(prefix="/ci", tags=["DevSecOps CI/CD"])


class CIGateRequest(BaseModel):
    repository: str = Field(..., description="Repository in 'owner/repo' format")
    commit_sha: str = Field(..., description="Git commit SHA being tested")
    branch: str = Field(default="main", description="Target branch")
    pr_number: Optional[int] = Field(default=None, description="Optional GitHub/GitLab PR number")
    findings: Optional[List[Dict[str, Any]]] = Field(
        default=None,
        description="Optional list of findings already generated by CI runners. If omitted, SageAI runs parallel matrix scanning.",
    )
    trigger_autofix: bool = Field(
        default=True,
        description="Whether to automatically trigger SagePatch fix PRs if the gate fails.",
    )


class CIPolicyUpdate(BaseModel):
    ci_fail_on_critical: Optional[bool] = Field(
        default=None, description="Block build if critical findings are detected"
    )
    ci_fail_on_high: Optional[bool] = Field(
        default=None, description="Block build if high findings are detected"
    )
    ci_auto_remediate: Optional[bool] = Field(
        default=None,
        description="Automatically open SagePatch PRs when policy is violated",
    )


@router.post("/gate")
@limiter.limit("60/minute")
async def evaluate_ci_gate(
    request: Request,
    payload: CIGateRequest,
    current_user: dict = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """Evaluate DevSecOps Security Quality Gate for a git commit or PR.

    Can be called directly from GitHub Actions or GitLab CI.
    Supports closed-loop auto-remediation PR creation via SagePatch.
    """
    org = await db.get(Organization, current_user["org"])
    if not org:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND, detail="Organization not found"
        )

    client_ip = request.client.host if request.client else None

    result = await execute_ci_gate_loop(
        db=db,
        org=org,
        repository=payload.repository,
        commit_sha=payload.commit_sha,
        branch=payload.branch,
        pr_number=payload.pr_number,
        provided_findings=payload.findings,
        trigger_autofix=payload.trigger_autofix,
        user_id=current_user.get("sub"),
        client_ip=client_ip,
    )

    return result


@router.get("/policy")
@limiter.limit("60/minute")
async def get_ci_policy(
    request: Request,
    current_user: dict = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """Retrieve organization DevSecOps CI Quality Gate policy thresholds."""
    org = await db.get(Organization, current_user["org"])
    if not org:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND, detail="Organization not found"
        )

    return {
        "organization": org.name,
        "ci_fail_on_critical": org.ci_fail_on_critical,
        "ci_fail_on_high": org.ci_fail_on_high,
        "ci_auto_remediate": org.ci_auto_remediate,
    }


@router.patch("/policy")
@limiter.limit("30/minute")
async def update_ci_policy(
    request: Request,
    payload: CIPolicyUpdate,
    current_user: dict = Depends(require_role("admin")),
    db: AsyncSession = Depends(get_db),
):
    """Update organization DevSecOps CI Quality Gate policy thresholds (admin only)."""
    org = await db.get(Organization, current_user["org"])
    if not org:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND, detail="Organization not found"
        )

    if payload.ci_fail_on_critical is not None:
        org.ci_fail_on_critical = payload.ci_fail_on_critical
    if payload.ci_fail_on_high is not None:
        org.ci_fail_on_high = payload.ci_fail_on_high
    if payload.ci_auto_remediate is not None:
        org.ci_auto_remediate = payload.ci_auto_remediate

    await db.commit()
    await db.refresh(org)

    await log_audit_event(
        db=db,
        organization_id=org.id,
        user_id=current_user.get("sub"),
        action="CI_POLICY_UPDATED",
        resource_type="ci_policy",
        details={
            "ci_fail_on_critical": org.ci_fail_on_critical,
            "ci_fail_on_high": org.ci_fail_on_high,
            "ci_auto_remediate": org.ci_auto_remediate,
        },
        ip_address=request.client.host if request.client else None,
    )

    return {
        "status": "updated",
        "organization": org.name,
        "ci_fail_on_critical": org.ci_fail_on_critical,
        "ci_fail_on_high": org.ci_fail_on_high,
        "ci_auto_remediate": org.ci_auto_remediate,
    }
