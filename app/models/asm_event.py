"""
SageAI 4.0 — ASM Event Model
Stores discrete events generated by the Continuous Attack Surface Management (ASM) diff engine.
"""

import enum

from sqlalchemy import Boolean, Column, DateTime, ForeignKey, String, Text
from sqlalchemy import Enum as SAEnum
from sqlalchemy.orm import relationship, synonym

from app.core.database import Base
from app.utils.helpers import generate_uuid, utc_now


class ASMEventType(str, enum.Enum):
    # Discovery events
    new_subdomain = "new_subdomain"
    new_ip = "new_ip"
    new_port = "new_port"
    new_service = "new_service"

    # State changes
    port_closed = "port_closed"
    service_changed = "service_changed"
    dns_changed = "dns_changed"

    # Vulnerability events
    new_vulnerability = "new_vulnerability"


class ASMEventSeverity(str, enum.Enum):
    info = "info"
    low = "low"
    medium = "medium"
    high = "high"
    critical = "critical"


class ASMEvent(Base):
    """Tracks discrete events generated by the Continuous ASM engine for alerting & timeline."""

    __tablename__ = "asm_events"

    id = Column(String, primary_key=True, default=generate_uuid)
    organization_id = Column(
        String,
        ForeignKey("organizations.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    org_id = synonym("organization_id")

    # Optional associations
    asset_id = Column(
        String, ForeignKey("assets.id", ondelete="CASCADE"), nullable=True, index=True
    )
    scan_id = Column(
        String, ForeignKey("scans.id", ondelete="SET NULL"), nullable=True, index=True
    )

    event_type = Column(SAEnum(ASMEventType), nullable=False, index=True)
    severity = Column(
        SAEnum(ASMEventSeverity), default=ASMEventSeverity.info, nullable=False
    )

    title = Column(String, nullable=False)
    description = Column(Text, nullable=True)

    # Stores precise change details depending on the event, e.g. {"port": 80, "service": "http"}
    details = Column(Text, default="{}")

    is_alert_sent = Column(Boolean, default=False)

    created_at = Column(DateTime(timezone=True), default=utc_now, index=True)

    # Relationships
    organization = relationship("Organization", back_populates="asm_events")
    asset = relationship("Asset", back_populates="asm_events")
    scan = relationship("Scan", back_populates="asm_events")
